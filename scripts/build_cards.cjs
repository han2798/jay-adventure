function extractCards(str) {
  const cards = new Map();
  const regex = /\{\s*id:\s*'(C[^']+)'/g;
  let match;
  while ((match = regex.exec(str)) !== null) {
    const id = match[1];
    const startIdx = match.index;
    let depth = 0;
    let endIdx = -1;
    let inString = false;
    let stringChar = '';
    let inLineComment = false;
    let inBlockComment = false;

    for (let i = startIdx; i < str.length; i++) {
      const char = str[i];
      const nextChar = str[i + 1];

      if (inLineComment) {
        if (char === '\n') inLineComment = false;
        continue;
      }
      if (inBlockComment) {
        if (char === '*' && nextChar === '/') {
          inBlockComment = false;
          i++;
        }
        continue;
      }
      if (inString) {
        if (char === '\\') {
          i++;
          continue;
        }
        if (char === stringChar) {
          inString = false;
        }
        continue;
      }

      if (char === '/' && nextChar === '/') {
        inLineComment = true;
        i++;
        continue;
      }
      if (char === '/' && nextChar === '*') {
        inBlockComment = true;
        i++;
        continue;
      }
      if (char === "'" || char === '"' || char === '`') {
        inString = true;
        stringChar = char;
        continue;
      }

      if (char === '{') {
        depth++;
      } else if (char === '}') {
        depth--;
        if (depth === 0) {
          endIdx = i + 1;
          break;
        }
      }
    }

    if (endIdx !== -1) {
      cards.set(id, str.slice(startIdx, endIdx));
    } else {
      console.error('Failed to find end of card:', id);
    }
  }
  return cards;
}

